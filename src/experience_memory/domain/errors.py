from enum import Enum


class ErrorCode(str, Enum):
    NOT_IMPLEMENTED = "NOT_IMPLEMENTED"
    NOT_CONFIGURED = "NOT_CONFIGURED"
    INVALID_INPUT = "INVALID_INPUT"
    INVALID_CONFIG = "INVALID_CONFIG"
    DISABLED = "DISABLED"
    INTERNAL_ERROR = "INTERNAL_ERROR"
    SCOPE_UNRESOLVED = "SCOPE_UNRESOLVED"
    CORE_INVALID = "CORE_INVALID"
    CORE_OVER_BUDGET = "CORE_OVER_BUDGET"
    POINTER_INVALID = "POINTER_INVALID"
    POINTER_IO_ERROR = "POINTER_IO_ERROR"
    LOCK_TIMEOUT = "LOCK_TIMEOUT"
    AUTHENTICATION_FAILED = "AUTHENTICATION_FAILED"
    REMOTE_FAILURE = "REMOTE_FAILURE"
    OPERATION_UNKNOWN = "OPERATION_UNKNOWN"
    OPERATION_PENDING = "OPERATION_PENDING"
    CONFLICT = "CONFLICT"
    NOT_FOUND = "NOT_FOUND"
    SCOPE_MISMATCH = "SCOPE_MISMATCH"
    HOST_SOURCE_UNVERIFIED = "HOST_SOURCE_UNVERIFIED"
    SESSION_INVALID = "SESSION_INVALID"
    NEEDS_REVIEW = "NEEDS_REVIEW"
    RECEIPT_INVALID = "RECEIPT_INVALID"
    CHECKPOINT_UNAVAILABLE = "CHECKPOINT_UNAVAILABLE"


class MemoryError(Exception):
    """Only code is safe to expose; arbitrary exception messages are private."""

    def __init__(self, code: ErrorCode):
        self.code = code
        super().__init__(code.value)
